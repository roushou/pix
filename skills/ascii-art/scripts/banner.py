def render(text, char):
    rows = ["" for _ in range(7)]
    for ch in text.upper():
        glyph = FONT.get(ch, FONT[" "])
        for i, row in enumerate(glyph):
            rows[i] += row.replace("#", char).replace(".", " ") + " "
    return "\n".join(r.rstrip() for r in rows)


def try_figlet(text, args):
    for cmd in ("toilet", "figlet"):
        path = shutil.which(cmd)
        if not path:
            continue
        argv = [path]
        if cmd == "toilet" and args.font:
            argv += ["-f", args.font]
        elif cmd == "figlet" and args.font:
            argv += ["-f", args.font]
        elif cmd == "figlet":
            argv += ["-f", "standard"]
        try:
            out = subprocess.run(argv + [text], capture_output=True, text=True, timeout=10)
            if out.returncode == 0 and out.stdout.strip():
                print(out.stdout.rstrip("\n"))
                return True
        except Exception:
            continue
    return False


def main():
    p = argparse.ArgumentParser(description="ASCII/Unicode text banner")
    p.add_argument("text", nargs="*", help="text to render (or pipe via stdin)")
    p.add_argument("--char", default="█", help="fill character for the built-in font (default █)")
    p.add_argument("--font", default=None, help="figlet/toilet font name")
    args = p.parse_args()

    text = " ".join(args.text)
    if not text and not sys.stdin.isatty():
        text = sys.stdin.read().strip()
    if not text:
        p.error("no text provided")

    if try_figlet(text, args):
        return
    print(render(text, args.char))


if __name__ == "__main__":
    main()
