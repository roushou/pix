// banner.ts — render text as a large ASCII/Unicode banner.
//
// Uses `figlet` or `toilet` when available (best results, many fonts), and
// falls back to a built-in 5x7 block font otherwise.
//
// Examples:
//   bun scripts/banner.ts 'pix'
//   bun scripts/banner.ts 'deploy' --char '#'
//   echo 'hello' | bun scripts/banner.ts

