function render(text: string, char: string): string {
  const rows: string[] = Array.from({ length: 7 }, () => "");
  for (const ch of text.toUpperCase()) {
    const glyph = FONT[ch] ?? FONT[" "] ?? [];
    for (let i = 0; i < 7; i++) {
      const cell = (glyph[i] ?? "").replaceAll("#", char).replaceAll(".", " ");
      rows[i] = `${rows[i] ?? ""}${cell} `;
    }
  }
  return rows.map((r) => r.replace(/\s+$/, "")).join("\n");
}

function tryFiglet(text: string, font?: string): boolean {
  for (const cmd of ["toilet", "figlet"] as const) {
    const argv: string[] = [];
    if (cmd === "toilet" && font) argv.push("-f", font);
    else if (cmd === "figlet" && font) argv.push("-f", font);
    else if (cmd === "figlet") argv.push("-f", "standard");
    argv.push(text);
    const res = spawnSync(cmd, argv, { encoding: "utf8", timeout: 10_000 });
    if (!res.error && res.status === 0 && (res.stdout ?? "").trim()) {
      process.stdout.write(`${(res.stdout ?? "").replace(/\n+$/, "")}\n`);
      return true;
    }
  }
  return false;
}

function fail(msg: string): never {
  console.error(`error: ${msg}`);
  process.exit(2);
}

function main(): void {
  const args = process.argv.slice(2);
  let char = "█";
  let font: string | undefined;
  const textParts: string[] = [];
  for (let i = 0; i < args.length; i++) {
    const a = args[i]!;
    if (a === "--char") {
      char = args[++i] ?? fail("--char requires a value");
    } else if (a === "--font") {
      font = args[++i] ?? fail("--font requires a value");
    } else if (a === "--help" || a === "-h") {
      console.log("usage: banner.ts [--char CHAR] [--font NAME] TEXT...");
      process.exit(0);
    } else {
      textParts.push(a);
    }
  }

  let text = textParts.join(" ");
  if (!text && !process.stdin.isTTY) {
    text = readFileSync(0, "utf8").trim();
  }
  if (!text) fail("no text provided");

  if (tryFiglet(text, font)) return;
  console.log(render(text, char));
}

main();
